export const FONT_HEIGHT = 7;
export const FONT_LINE_HEIGHT = 10;

export interface GlyphRect {
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface FontAtlas {
  raster: Raster;
  glyphs: Map<string, GlyphRect>;
}

export function buildFontAtlas(): FontAtlas {
  const entries = Object.entries(G).map(([ch, def]) => {
    const rows = def.split('/');
    if (rows.length !== FONT_HEIGHT) throw new Error(`Glyph '${ch}' has ${rows.length} rows`);
    const w = Math.max(...rows.map((r) => r.length));
    return { ch, rows, w };
  });
  const width = entries.reduce((s, e) => s + e.w + 1, 1);
  const raster = new Raster(width, FONT_HEIGHT + 2);
  const white = rgba(255, 255, 255);
  const glyphs = new Map<string, GlyphRect>();
  let x = 1;
  for (const e of entries) {
    e.rows.forEach((row, y) => {
      for (let i = 0; i < row.length; i++) if (row[i] === '#') raster.set(x + i, y + 1, white);
    });
    glyphs.set(e.ch, { x, y: 1, w: e.w, h: FONT_HEIGHT });
    x += e.w + 1;
  }
  return { raster, glyphs };
}

/** Width in pixels of a string at scale 1 (1px letter spacing). */
export function measureText(atlas: FontAtlas, text: string): number {
  let w = 0;
  for (const ch of text.toUpperCase()) {
    const g = atlas.glyphs.get(ch) ?? atlas.glyphs.get('?')!;
    w += g.w + 1;
  }
  return Math.max(0, w - 1);
}
